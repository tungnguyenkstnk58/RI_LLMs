function ids = nearestTokenIds(Xa, E, P)

% Approximate decoding by nearest token embeddings.

[~, L] = size(Xa);
V = size(E, 2);
ids = zeros(1, L);
for j = 1:L
    bestDist = inf;
    bestId = 1;
    for i = 1:V
        candidate = E(:,i) + P(:,j);
        dist = sum((Xa(:,j) - candidate).^2);
        if dist < bestDist
            bestDist = dist;
            bestId = i;
        end
    end
    ids(j) = bestId;
end
end

