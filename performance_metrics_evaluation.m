function performance_metrics_evaluation()
% PERFORMANCE_METRICS_EVALUATION
% ------------------------------------------------------------
% Main evaluation script for the paper experiments.
%
% Purpose:
%   1. Load the trained multi-head attention benchmark.
%   2. Compute the bounded-rationality metric on clean validation prompts.
%   3. Evaluate stealthy attacks under the proposed safety metric.
%   4. Save numerical summaries and figures for the paper.
%
% Required input file:
%   trained_multihead_english_attention.mat
% ------------------------------------------------------------
clear; %#ok
% clc; close all;

%% Load trained model and validation prompts
% Load the trained attention model and validation prompts generated by the
% training script. The learned matrices are converted to double precision
% for numerical evaluation. The vocabulary is stored globally so that
% perturbed embedding sequences can be approximately decoded into text.
S = load('trained_multihead_english_attention.mat', 'model', 'cfg', 'dataVal', 'vocab', 'corpus');
model = castModelToDouble(S.model);
cfg = S.cfg;
dataVal = S.dataVal;
vocab = S.vocab;
corpus = S.corpus; %#ok<NASGU>
global EXP_VOCAB;
EXP_VOCAB = vocab;

%% Experiment configuration
% Configure the clean bounded-rationality evaluation and the attacks
% used for the safety-metric illustration.
%
% cfgExp3.attackModes:
%   'all'     : attack all history tokens,
%   'subject' : attack only the subject token,
%   'object'  : attack only the object token.
%
% cfgExp3.epsilon sets the stealth tolerance, cfgExp3.rho sets the attack
% energy budget, and cfgExp3.nTrials sets the number of Monte Carlo trials.
cfgExp2.numPromptExamples = 6;

cfgExp3.numExamples = 2;
cfgExp3.attackModes = {'all','subject','object'};
cfgExp3.epsilon = 1;                  % stealth tolerance
cfgExp3.rho = 30;                     % attack energy budget
cfgExp3.nTrials = 7000;               % Monte Carlo trials
cfgExp3.w = ones(1, cfg.mHeads) / cfg.mHeads;
cfgExp3.useClosedFormIfAvailable = true;
cfgExp3.fallbackToMonteCarlo = true;

%% Build a deterministic clean prompt set from unique validation prompts
% Remove duplicate validation contexts so that the reported examples are
% deterministic and each prompt is counted once in the clean metric summary.
samplesUnique = uniquePromptSamples(dataVal);
fprintf('Unique validation prompts available: %d\n', numel(samplesUnique));
if isempty(samplesUnique)
    error('No unique validation prompts found. Train the model first.');
end

%% ======================= Experiment 2 =======================
% Compute the head-wise bounded-rationality metric on clean validation
% prompts. The results summarize how the metric varies across prompts and
% across attention heads
exp2 = runExperiment2CleanMetric(model, samplesUnique, vocab, cfg, cfgExp2);
save('exp2_metric_summary.mat', 'exp2');
fprintf('Saved Experiment 2 summary to exp2_metric_summary.mat\n');
printExperiment2Summary(exp2);

%% ======================= Experiment 3 =======================
% Evaluate the safety metric under attacks. For each
% selected prompt and attack mode, the script first attempts a closed-form
% nullspace-based attack and falls back to Monte Carlo search if needed
cfgExp3.sampleIndices = [2 3];   % example: choose the 3rd and 17th unique prompts
exp3Samples = samplesUnique(cfgExp3.sampleIndices);
exp3 = runExperiment3Security(model, exp3Samples, vocab, cfg, cfgExp3);
save('exp3_security_summary.mat', 'exp3');
fprintf('Saved Experiment 3 summary to exp3_security_summary.mat\n');
printExperiment3Summary(exp3);

end

%% ========================= Experiment 2 =========================
function exp2 = runExperiment2CleanMetric(model, samplesUnique, vocab, cfg, cfgExp2)
% Evaluate clean bounded-rationality metrics.
%
% Purpose:
%   Compute the head-wise bounded-rationality metric on clean validation
%   prompts. The function also computes summary statistics, stores predicted
%   tokens, selects representative examples, and generates diagnostic plots.
%
% Inputs:
%   model         : numeric struct containing trained model matrices.
%   samplesUnique : struct array of unique validation prompts.
%   vocab         : vocabulary string array.
%   cfg           : configuration struct containing model dimensions and tau.
%   cfgExp2       : Experiment 2 configuration, including number of examples.
%
% Output:
%   exp2          : struct containing:
%                   samplesUnique, deltaV, avgDeltaV, predTexts,
%                   statsByHead, statsAvg, examples.

N = numel(samplesUnique);
deltaV = zeros(N, cfg.mHeads);
avgDeltaV = zeros(N,1);
preds = strings(N,1);

for n = 1:N
    clean = forwardOneNumeric(model, samplesUnique(n).context, cfg);
    for m = 1:cfg.mHeads
        deltaV(n,m) = clean.heads(m).deltaV;
    end
    avgDeltaV(n) = mean(deltaV(n,:));
    preds(n) = string(vocab(clean.pred));
    samplesUnique(n).clean = clean; %#ok<AGROW>
end

stats = struct();
for m = 1:cfg.mHeads
    stats(m).mean = mean(deltaV(:,m));
    stats(m).std = std(deltaV(:,m));
    stats(m).median = median(deltaV(:,m));
    stats(m).min = min(deltaV(:,m));
    stats(m).max = max(deltaV(:,m));
end
statsAvg.mean = mean(avgDeltaV);
statsAvg.std = std(avgDeltaV);
statsAvg.median = median(avgDeltaV);
statsAvg.min = min(avgDeltaV);
statsAvg.max = max(avgDeltaV);

idxExample = 1:min(cfgExp2.numPromptExamples, N);
examples = samplesUnique(idxExample);

% Save example-level table structure
for i = 1:numel(examples)
    examples(i).predText = preds(idxExample(i)); %#ok<AGROW>
    examples(i).deltaV = deltaV(idxExample(i),:); %#ok<AGROW>
    examples(i).avgDeltaV = avgDeltaV(idxExample(i)); %#ok<AGROW>
end

% Boxplot figure
fig1 = figure('Name','Experiment 2 Boxplot','Color','w');
boxplot([deltaV avgDeltaV], 'Labels', buildMetricLabels(cfg.mHeads));
ylabel('Bounded rationality metric value');
grid on;
title('Experiment 2: clean bounded-rationality metrics over unique prompts');
saveas(fig1, 'exp2_metric_boxplot.png');

% Example attention figure
fig2 = figure('Name','Experiment 2 Clean Attention Examples','Color','w');
numEx = numel(examples);
for i = 1:numEx
    clean = examples(i).clean;
    for m = 1:cfg.mHeads
        subplot(numEx, cfg.mHeads, (i-1)*cfg.mHeads + m);
        bar(clean.heads(m).alpha, 'FaceColor', [0.20 0.45 0.85]);
        grid on;
        title(sprintf('Ex %d Head %d | DV=%.4f', i, m, clean.heads(m).deltaV));
        xlabel('History pos'); ylabel('alpha');
    end
end
sgtitle('Experiment 2: clean attention distributions for representative prompts');
saveas(fig2, 'exp2_metric_examples.png');

exp2.samplesUnique = rmfieldIfExists(samplesUnique, 'clean');
exp2.deltaV = deltaV;
exp2.avgDeltaV = avgDeltaV;
exp2.predTexts = preds;
exp2.statsByHead = stats;
exp2.statsAvg = statsAvg;
exp2.examples = examples;
end

function printExperiment2Summary(exp2)
fprintf('\n================ Experiment 2 ================\n');
for m = 1:numel(exp2.statsByHead)
    s = exp2.statsByHead(m);
    fprintf('Head %d: mean %.4f | std %.4f | median %.4f | min %.4f | max %.4f\n', ...
        m, s.mean, s.std, s.median, s.min, s.max);
end
fprintf('Average over heads: mean %.4f | std %.4f | median %.4f | min %.4f | max %.4f\n', ...
    exp2.statsAvg.mean, exp2.statsAvg.std, exp2.statsAvg.median, exp2.statsAvg.min, exp2.statsAvg.max);

fprintf('\nRepresentative prompts (up to 6):\n');
for i = 1:numel(exp2.examples)
    ex = exp2.examples(i);
    fprintf('Ex %d | "%s" | pred="%s" | ', i, ex.contextText, ex.predText);
    fprintf('DeltaV = [');
    fprintf('%.4f ', ex.deltaV);
    fprintf('] | avg = %.4f\n', ex.avgDeltaV);
end
fprintf('Figures saved: exp2_metric_boxplot.png and exp2_metric_examples.png\n');
end

%% ========================= Experiment 3 =========================
function exp3 = runExperiment3Security(model, exp3Samples, vocab, cfg, cfgExp3)
% Evaluate safety metric under attacks.
%
% Purpose:
%   For each selected prompt and attack mode, compute a clean forward pass,
%   define the clean bounded-rationality monitoring value, and search for a
%   stealthy perturbation that maximizes the internal representation shift.
%   The function stores quantitative results and generates attack-case
%   attention plots.
%
% Inputs:
%   model       : numeric struct containing trained model matrices.
%   exp3Samples : struct array of selected validation prompts.
%   vocab       : vocabulary string array.
%   cfg         : configuration struct.
%   cfgExp3     : Experiment 3 configuration, including attack modes,
%                 epsilon, rho, nTrials, weights, and solver flags.
%
% Output:
%   exp3        : struct containing:
%                 results  = all attack results,
%                 examples = representative results selected for plotting.

numExamples = numel(exp3Samples);
results = struct('contextText', {}, 'targetText', {}, 'cleanPredText', {}, ...
                 'attackMode', {}, 'method', {}, 'metricValue', {}, ...
                 'stealthResidual', {}, 'attackEnergy', {}, ...
                 'attackedPredText', {}, 'predictionChanged', {}, ...
                 'cleanDeltaV', {}, 'attackedDeltaV', {}, ...
                 'approxAttackedText', {}, 'supportIdx', {}, ...
                 'clean', {}, 'attackResult', {});

count = 0;
for e = 1:numExamples
    sample = exp3Samples(e);
    clean = forwardOneNumeric(model, sample.context, cfg);
    theta = zeros(1, cfg.mHeads);
    for m = 1:cfg.mHeads
        theta(m) = clean.heads(m).deltaV;
    end

    for a = 1:numel(cfgExp3.attackModes)
        mode = cfgExp3.attackModes{a};
        supportIdx = resolveAttackSupport(mode, cfg);

        % 1) Try closed-form attack if enabled
        best = [];
        usedMethod = '';
        if cfgExp3.useClosedFormIfAvailable
            try
                bestCF = computeClosedFormAttack(model, sample, clean, cfg, cfgExp3, theta, supportIdx);
                if ~isempty(bestCF)
                    best = bestCF;
                    usedMethod = 'closed-form';
                end
            catch ME
                warning('Closed-form attack failed for mode=%s: %s', mode, ME.message);
            end
        end

        % 2) Fallback to Monte Carlo if needed
        if isempty(best) && cfgExp3.fallbackToMonteCarlo
            best = estimateMetricMonteCarlo(model, sample, cfg, cfgExp3, theta, supportIdx);
            usedMethod = 'monte-carlo';
        end

        if isempty(best)
            error('Neither closed-form nor Monte Carlo attack produced a result.');
        end

        count = count + 1;
        results(count).contextText = sample.contextText;
        results(count).targetText = string(sample.targetText);
        results(count).cleanPredText = string(vocab(clean.pred));
        results(count).attackMode = string(mode);
        results(count).method = string(usedMethod);
        results(count).metricValue = best.metricValue;
        results(count).stealthResidual = best.stealthResidual;
        results(count).attackEnergy = best.attackEnergy;
        results(count).attackedPredText = string(vocab(best.pred_a));
        results(count).predictionChanged = ~strcmp(results(count).cleanPredText, results(count).attackedPredText);
        results(count).cleanDeltaV = theta;
        results(count).attackedDeltaV = best.deltaV_a;
        results(count).approxAttackedText = best.approxAttackedText;
        results(count).supportIdx = supportIdx;
        results(count).clean = clean;
        results(count).attackResult = best;
    end
end

% Select one representative result per example for plotting and text display
examples = chooseRepresentativeResults(results, numExamples, cfgExp3.attackModes);
for e = 1:numel(examples)
    fig = plotExp3Case(examples(e), e, cfg);
    set(gcf, 'Position', [200 200 800 250]);
    saveas(fig, sprintf('exp3_case_example_%d.png', e));
end

exp3.results = results;
exp3.examples = examples;
end

function printExperiment3Summary(exp3)
fprintf('\n================ Experiment 3 ================\n');
for i = 1:numel(exp3.results)
    r = exp3.results(i);
    fprintf('Context="%s" | mode=%s | method=%s | metric=%.4f | stealth=%.4e | energy=%.4f | %s -> %s | changed=%d\n', ...
        r.contextText, r.attackMode, r.method, r.metricValue, r.stealthResidual, r.attackEnergy, ...
        r.cleanPredText, r.attackedPredText, r.predictionChanged);
end

fprintf('\nTwo representative manipulated-text examples:\n');
for e = 1:numel(exp3.examples)
    ex = exp3.examples(e);
    fprintf('Example %d | mode=%s | method=%s\n', e, ex.attackMode, ex.method);
    fprintf('  Clean context           : %s\n', ex.contextText);
    fprintf('  Approx. attacked context: %s\n', ex.approxAttackedText);
    fprintf('  Predicted next token    : %s -> %s\n', ex.cleanPredText, ex.attackedPredText);
end
fprintf('Figures saved: exp3_case_example_1.png, exp3_case_example_2.png\n');
end

%% ========================= Attack solvers =========================
function result = computeClosedFormAttack(model, sample, clean, cfg, cfgExp3, theta, supportIdx)

% Closed-form nullspace-based attacks.
%
% Purpose:
%   Construct a perfectly-undetectable attack candidate using the common
%   nullspace of all key matrices Wk(:,:,m). The attack direction maximizes
%   the representation shift under the energy budget within the selected
%   attack support. If the resulting perturbation fails the practical
%   stealth check, the function returns empty.
%
% Inputs:
%   model      : numeric struct containing trained model matrices.
%   sample     : validation sample being attacked.
%   clean      : clean forward-pass output for the sample.
%   cfg        : configuration struct.
%   cfgExp3    : Experiment 3 configuration with rho, epsilon, weights.
%   theta      : clean head-wise bounded-rationality values.
%   supportIdx : token positions allowed to be perturbed.
%
% Output:
%   result     : struct containing attack metric value, attacked metrics,
%                attacked prediction, attack energy, stealth residual,
%                attack vector, attacked embeddings, and approximate
%                attacked text. Returns [] if no valid closed-form attack
%                is available.


Nk = commonNullspaceBasis(model, cfg);
if isempty(Nk)
    result = [];
    return;
end

% Build F = [B_i*Nk] over supported history positions only.
historySupport = supportIdx(supportIdx <= cfg.L-1);
if isempty(historySupport)
    result = [];
    return;
end

F = [];
for idx = historySupport
    Bi = computeBi(model, clean, cfg, idx);
    F = [F, Bi * Nk]; %#ok<AGROW>
end

if isempty(F) || rank(F) == 0
    result = [];
    return;
end

Q = F' * F;
[vecs, vals] = eig((Q + Q')/2);
[~, ind] = max(real(diag(vals)));
v = real(vecs(:,ind));
if norm(v) < 1e-12
    result = [];
    return;
end
v = v / norm(v);
c = sqrt(cfgExp3.rho) * v;

% Convert c into token perturbations A(:,idx) = Nk * c_i
r = size(Nk,2);
A = zeros(cfg.d, cfg.L);
ptr = 1;
for idx = historySupport
    seg = c(ptr:ptr+r-1);
    ptr = ptr + r;
    A(:,idx) = Nk * seg;
end

bestOut = perturbedForward(A(:), model, clean.X, cfg);
stealthResidual = weightedStealth(theta, bestOut.deltaV_a, cfgExp3.w);

% If the perfect-undetectability idea is numerically inconsistent with the
% practical stealth check, reject and let the caller fallback to MC.
if stealthResidual > cfgExp3.epsilon + 1e-9
    result = [];
    return;
end

metricVal = sum((bestOut.hCombined_a - clean.hCombined).^2);
result.metricValue = double(metricVal);
result.deltaV_a = double(bestOut.deltaV_a(:)');
result.hCombined_a = double(bestOut.hCombined_a);
result.alpha_a = bestOut.alpha_a;
result.pred_a = double(bestOut.pred_a);
result.attackEnergy = double(sum(A(:).^2));
result.stealthResidual = double(stealthResidual);
result.attackVector = A;
result.Xa = bestOut.Xa;
result.approxAttackedText = bestOut.approxAttackedText;
end

function result = estimateMetricMonteCarlo(model, sample, cfg, cfgMetric, theta, supportIdx)

% Randomized bounded attacks.
%
% Purpose:
%   Approximate the safety metric by randomly sampling attacks within
%   the energy budget and keeping only those satisfying the stealth
%   constraint. Among feasible attacks, return the one that maximizes
%   the squared shift of the combined internal representation.
%
% Inputs:
%   model      : numeric struct containing trained model matrices.
%   sample     : validation sample being attacked.
%   cfg        : configuration struct.
%   cfgMetric  : metric/attack configuration with epsilon, rho, nTrials,
%                and weights.
%   theta      : clean head-wise bounded-rationality values.
%   supportIdx : token positions allowed to be attacked.
%
% Output:
%   result     : struct containing the best feasible attack result:
%                metricValue, deltaV_a, hCombined_a, alpha_a, pred_a,
%                attackEnergy, stealthResidual, attackVector, Xa,
%                approxAttackedText.

clean = forwardOneNumeric(model, sample.context, cfg);
Xclean = clean.X;
[d, L] = size(Xclean);

bestVal = -inf;
bestOut = [];
bestZ = zeros(d*L,1);

for k = 1:cfgMetric.nTrials
    zMat = zeros(d, L);
    zSupport = randn(d, numel(supportIdx));
    zSupport = zSupport / max(norm(zSupport(:)), 1e-12);
    radius = sqrt(cfgMetric.rho) * rand();
    zSupport = radius * zSupport;
    zMat(:, supportIdx) = zSupport;
    z = zMat(:);

    out = perturbedForward(z, model, Xclean, cfg);
    stealthResidual = weightedStealth(theta, out.deltaV_a, cfgMetric.w);

    if stealthResidual <= cfgMetric.epsilon
        metricVal = sum((out.hCombined_a - clean.hCombined).^2);
        if metricVal > bestVal
            bestVal = metricVal;
            bestOut = out;
            bestZ = z;
        end
    end
end

if isempty(bestOut)
    warning('No feasible Monte Carlo perturbation found under current epsilon/rho settings. Returning clean sample.');
    bestOut = perturbedForward(zeros(d*L,1), model, Xclean, cfg);
    bestVal = 0;
    bestZ = zeros(d*L,1);
end

stealthResidual = weightedStealth(theta, bestOut.deltaV_a, cfgMetric.w);
A = reshape(bestZ, d, L);
result.metricValue = double(bestVal);
result.deltaV_a = double(bestOut.deltaV_a(:)');
result.hCombined_a = double(bestOut.hCombined_a);
result.alpha_a = bestOut.alpha_a;
result.pred_a = double(bestOut.pred_a);
result.attackEnergy = double(sum(bestZ.^2));
result.stealthResidual = double(stealthResidual);
result.attackVector = A;
result.Xa = bestOut.Xa;
result.approxAttackedText = bestOut.approxAttackedText;
end

%% ========================= Core forward passes =========================
function out = perturbedForward(z, model, Xclean, cfg)

% Forward pass under embedding attacks.
%
% Purpose:
%   Apply an attack to the clean embedded context, compute the attacked
%   attention scores/weights, attacked bounded-rationality values, attacked
%   internal representation, output probabilities, and predicted token.
%   The attacked embedding sequence is also approximately decoded to the
%   nearest vocabulary tokens for qualitative display.
%
% Inputs:
%   z      : vectorized perturbation of size d*L.
%   model  : numeric struct containing trained model matrices.
%   Xclean : clean embedded context matrix of size d-by-L.
%   cfg    : configuration struct.
%
% Output:
%   out    : struct containing:
%            Xa                 = attacked embedded context,
%            hCombined_a        = attacked combined representation,
%            logits_a, prob_a   = attacked logits and probabilities,
%            pred_a             = attacked predicted token ID,
%            deltaV_a           = attacked

[d, L] = size(Xclean);
A = reshape(z, d, L);
Xa = double(Xclean) + double(A);
Xhist = Xa(:,1:end-1);
xq = Xa(:,end);

hCat = [];
deltaV_a = zeros(1, cfg.mHeads);
alpha_a = cell(1, cfg.mHeads);
for l = 1:cfg.mHeads
    q_a = model.Wq(:,:,l) * xq;
    K_a = model.Wk(:,:,l) * Xhist;
    V_a = model.Wv(:,:,l) * Xhist;
    scores_a = q_a' * K_a;
    alpha_l = softmaxRowNumeric(scores_a / cfg.tau);
    h_l = V_a * alpha_l';
    deltaV_l = cfg.tau * logsumexpNumeric(scores_a / cfg.tau) - max(scores_a);
    alpha_a{l} = alpha_l;
    deltaV_a(l) = deltaV_l;
    hCat = [hCat; h_l]; %#ok<AGROW>
end

hCombined_a = model.Wo * hCat;
logits_a = model.U' * hCombined_a + model.b;
prob_a = softmaxColNumeric(logits_a);
[~, pred_a] = max(prob_a);

% Approximate nearest-token decoding for qualitative display
approxAttackedIds = nearestTokenIds(Xa, model.E, model.P);
global EXP_VOCAB; approxAttackedText = idsToText(approxAttackedIds, EXP_VOCAB);

out.Xa = Xa;
out.hCombined_a = hCombined_a;
out.logits_a = logits_a;
out.prob_a = prob_a;
out.pred_a = pred_a;
out.deltaV_a = deltaV_a;
out.alpha_a = alpha_a;
out.approxAttackedText = approxAttackedText;
end

function out = forwardOneNumeric(model, contextIds, cfg)

% Clean numeric forward pass for one context.
%
% Purpose:
%   Compute the model output for a clean context using ordinary numeric
%   arrays. This function also computes and stores all head-wise quantities
%   required for the bounded-rationality metric.
%
% Inputs:
%   model      : numeric struct containing trained model matrices.
%   contextIds : row vector of context token IDs of length cfg.L.
%   cfg        : configuration struct.
%
% Output:
%   out        : struct containing:
%                X          = clean embedded context with position encoding,
%                heads      = per-head scores, alpha, h, deltaV,
%                hCat       = concatenated head outputs,
%                hCombined  = combined internal representation,
%                logits     = clean logits,
%                prob       = clean output probabilities

X = double(model.E(:, contextIds) + model.P);
Xhist = X(:,1:end-1);
xq = X(:,end);
heads = struct('scores', cell(1,cfg.mHeads), 'alpha', cell(1,cfg.mHeads), ...
               'h', cell(1,cfg.mHeads), 'deltaV', cell(1,cfg.mHeads));
hCat = [];
for l = 1:cfg.mHeads
    q = model.Wq(:,:,l) * xq;
    K = model.Wk(:,:,l) * Xhist;
    V = model.Wv(:,:,l) * Xhist;
    scores = q' * K;
    alpha = softmaxRowNumeric(scores / cfg.tau);
    h_l = V * alpha';
    deltaV = cfg.tau * logsumexpNumeric(scores / cfg.tau) - max(scores);
    heads(l).scores = scores;
    heads(l).alpha = alpha;
    heads(l).h = h_l;
    heads(l).deltaV = deltaV;
    hCat = [hCat; h_l]; %#ok<AGROW>
end
hCombined = model.Wo * hCat;
logits = model.U' * hCombined + model.b;
prob = softmaxColNumeric(logits);
[~, pred] = max(prob);
out.X = X;
out.heads = heads;
out.hCat = hCat;
out.hCombined = hCombined;
out.logits = logits;
out.prob = prob;
out.pred = pred;
end

%% ========================= Utility / selection helpers =========================
function samplesUnique = uniquePromptSamples(dataVal)

% Select unique validation contexts.
%
% Purpose:
%   Remove duplicate validation samples based on their context text while
%   preserving first-occurrence order. This provides deterministic clean
%   prompt sets for reporting and case studies.
%
% Input:
%   dataVal       : validation

seen = containers.Map('KeyType','char','ValueType','logical');
keep = false(1, numel(dataVal));
for i = 1:numel(dataVal)
    key = char(dataVal(i).contextText);
    if ~isKey(seen, key)
        seen(key) = true;
        keep(i) = true;
    end
end
samplesUnique = dataVal(keep);
end

function samples = chooseExp3Samples(samplesUnique, k)

% Select representative prompts for Experiment 3.

if numel(samplesUnique) <= k
    samples = samplesUnique;
    return;
end
idx = round(linspace(1, numel(samplesUnique), k));
idx = unique(idx, 'stable');
samples = samplesUnique(idx);
if numel(samples) < k
    extra = setdiff(1:numel(samplesUnique), idx, 'stable');
    samples = [samples, samplesUnique(extra(1:(k-numel(samples))))]; %#ok<AGROW>
end
end

function labels = buildMetricLabels(mHeads)

% Build plot labels for head-wise metrics

labels = cell(1, mHeads+1);
for i = 1:mHeads
    labels{i} = sprintf('Head %d', i);
end
labels{mHeads+1} = 'Average';
end

function supportIdx = resolveAttackSupport(mode, cfg)

% Convert attack mode to perturbed token positions.

mode = lower(string(mode));
switch mode
    case "all"
        supportIdx = 1:(cfg.L-1); % theory-consistent: attack only history tokens
    case "subject"
        supportIdx = cfg.subjectIndex;
    case "object"
        supportIdx = cfg.objectIndex;
    otherwise
        error('Unknown attack mode: %s', mode);
end
supportIdx = unique(supportIdx(:)');
end

function val = weightedStealth(theta, deltaVa, w)

% Compute weighted stealth residual.

val = 0;
for l = 1:numel(theta)
    val = val + w(l) * (theta(l) - deltaVa(l))^2;
end
end

