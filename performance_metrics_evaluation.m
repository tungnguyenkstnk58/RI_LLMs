function Bi = computeBi(model, clean, cfg, historyPos)

% Compute representation-shift map for one token position

Bi = zeros(cfg.dComb, cfg.d);
for m = 1:cfg.mHeads
    cols = (m-1)*cfg.dv + (1:cfg.dv);
    WoBlock = model.Wo(:, cols);
    alpha_i = clean.heads(m).alpha(historyPos);
    Bi = Bi + WoBlock * (alpha_i * model.Wv(:,:,m));
end
end

